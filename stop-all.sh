#!/bin/bash
# ============================================
# 一键停止三个服务
# ============================================

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo "=========================================="
echo "  正在停止所有服务..."
echo "=========================================="

# 通过 cmd.exe 执行 Windows 命令，避免 bash 路径转义问题
cmd.exe //c "taskkill /F /IM java.exe /T 2>nul" && echo "  已停止 Java 后端"
cmd.exe //c "taskkill /F /IM node.exe /T 2>nul" && echo "  已停止 Node 前端"

sleep 1

echo -e "${GREEN}=========================================="
echo "  所有服务已停止"
echo -e "==========================================${NC}"
